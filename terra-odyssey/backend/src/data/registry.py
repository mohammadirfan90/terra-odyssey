def find_entry(dataset_id: str) -> Optional[DatasetRegistryEntry]:
    """Find a dataset registry entry by ID or alias."""
    for entry in _REGISTRY:
        if entry.matches(dataset_id):
            return entry
    return None


def resolve_adapter(dataset_id: str, variable: str) -> tuple[Any, DatasetRegistryEntry]:
    """Resolve and validate an adapter for execution.

    Raises UnsupportedDatasetError if:
    - The dataset is unknown
    - The variable is not supported for that dataset
    - The dataset capability does not support quantitative trend estimation
    - The adapter class is not yet implemented
    """
    entry = find_entry(dataset_id)
    if entry is None:
        raise UnsupportedDatasetError(
            f"Dataset '{dataset_id}' is not recognized in the Terra Odyssey catalog.",
            invalid_params=[{"name": "dataset_id", "value": dataset_id}],
        )

    var_clean = (variable or "").strip()
    var_matches = any(var_clean.lower() == sv.lower() for sv in entry.supported_variables)
    if not var_matches:
        raise UnsupportedDatasetError(
            f"Variable '{variable}' is not supported for dataset '{entry.name}'. Supported: {entry.supported_variables}",
            invalid_params=[{"name": "variable", "value": variable, "supported": entry.supported_variables}],
        )

    if not (entry.capabilities.trend_supported or entry.capabilities.series_supported):
        reason = entry.capabilities.unsupported_reason or "Quantitative trend analysis is not yet activated for this product."
        raise UnsupportedDatasetError(
            f"Dataset '{entry.name}' is discoverable but cannot be analyzed: {reason}",
            invalid_params=[{"name": "dataset_id", "value": dataset_id, "capabilities": entry.capabilities.model_dump()}],
        )

    if entry.adapter_class is None:
        raise UnsupportedDatasetError(
            f"Adapter implementation for '{entry.name}' is scheduled in an upcoming milestone phase.",
            invalid_params=[{"name": "dataset_id", "value": dataset_id}],
        )

    adapter_inst = entry.adapter_class()
    return adapter_inst, entry


def build_catalog_items() -> Dict[str, DatasetCatalogItem]:
    """Construct catalog items with truthful capabilities and manifest metadata."""
    catalog: Dict[str, DatasetCatalogItem] = {}

    for entry in _REGISTRY:
        manifest_data = _load_manifest(entry.manifest_name) or {}

        quality_policy = manifest_data.get("quality_policy", {
            "fill_values": ["preserve source fill value"],
            "mask_description": "Validate source fill and coordinate metadata.",
            "qa_fields": [],
        })

        provenance = manifest_data.get("provenance", {
            "documentation_urls": [entry.citation_doi] if entry.citation_doi else [],
            "provider": entry.provider,
        })

        catalog[entry.dataset_id] = DatasetCatalogItem(
            dataset_id=entry.dataset_id,
            name=entry.name,
            collection=entry.collection,
            version=entry.version,
            topic=entry.topic,
            provider=entry.provider,
            concept_id=entry.concept_id,
            native_resolution=entry.native_resolution,
            license=entry.license,
            citation_doi=entry.citation_doi,
            gibs_layer=entry.gibs_layer,
            source_type=entry.source_type,
            variable=entry.variable,
            units=entry.units,
            spatial_support=entry.spatial_support,
            temporal_support=entry.temporal_support,
            coverage_start=entry.coverage_start,
            coverage_end=entry.coverage_end,
            quality_policy=quality_policy,
            provenance=provenance,
            capabilities=entry.capabilities,
            supported_aggregations=entry.supported_aggregations,
            supported_spatial_aggregations=entry.supported_spatial_aggregations,
            categories=entry.categories,
        )

    return catalog


def get_dataset_availability(dataset_id: str) -> DatasetAvailabilityResponse:
    """Calculate granule presence, archive availability, and scientific eligibility spans."""
    entry = find_entry(dataset_id)
    if entry is None:
        raise UnsupportedDatasetError(
            f"Dataset '{dataset_id}' not found in catalog.",
            invalid_params=[{"name": "dataset_id", "value": dataset_id}],
        )

    start_year = int(entry.coverage_start.split("-")[0])
    end_year = int((entry.coverage_end or datetime.now().strftime("%Y-%m-%d")).split("-")[0])

    # Determine complete calendar years
    # If start is mid-year (e.g. 2000-06-01), the first complete year is start_year + 1
    start_month = int(entry.coverage_start.split("-")[1])
    first_complete_year = start_year if start_month == 1 else start_year + 1

    end_month = int((entry.coverage_end or "2024-12-31").split("-")[1])
    last_complete_year = end_year if end_month == 12 else end_year - 1

    years_available = list(range(start_year, end_year + 1))
    complete_years_count = max(0, last_complete_year - first_complete_year + 1)
    total_years = len(years_available)
    completeness_pct = round((complete_years_count / total_years) * 100.0, 1) if total_years > 0 else 0.0

    # Eligible spans for statistical trend analysis (minimum 20 consecutive complete years)
    eligible_spans = []
    if complete_years_count >= 20:
        eligible_spans.append(
            EligibleSpan(
                start_year=first_complete_year,
                end_year=last_complete_year,
                complete_years=complete_years_count,
                is_eligible=True,
            )
        )
    else:
        eligible_spans.append(
            EligibleSpan(
                start_year=first_complete_year,
                end_year=last_complete_year,
                complete_years=complete_years_count,
                is_eligible=False,
            )
        )

    gaps = [
        AvailabilityGap(
            start_date=g["start_date"],
            end_date=g["end_date"],
            description=g["description"],
        )
        for g in entry.gaps
    ]

    return DatasetAvailabilityResponse(
        dataset_id=entry.dataset_id,
        name=entry.name,
        temporal_support=entry.temporal_support,
        coverage_start=entry.coverage_start,
        coverage_end=entry.coverage_end or f"{end_year}-12-31",
        total_years=total_years,
        complete_years=complete_years_count,
        completeness_pct=completeness_pct,
        gaps=gaps,
        eligible_spans=eligible_spans,
        years_available=years_available,
        gibs_layer=entry.gibs_layer,
    )
