@dataclass
class DatasetRegistryEntry:
    """Registration record for an evaluated NASA Earth system dataset."""

    dataset_id: str
    aliases: List[str]
    name: str
    collection: str
    version: str
    topic: str
    provider: str
    source_type: str
    variable: str
    supported_variables: List[str]
    units: str
    spatial_support: str
    temporal_support: str
    coverage_start: str
    coverage_end: Optional[str]
    manifest_name: str
    adapter_class: Optional[Type[Any]]
    capabilities: DatasetCapabilities
    concept_id: Optional[str] = None
    native_resolution: Optional[str] = None
    license: str = "NASA Open Data Policy"
    citation_doi: Optional[str] = None
    gibs_layer: Optional[str] = None
    supported_aggregations: List[str] = field(
        default_factory=lambda: ["annual_mean", "annual_total", "seasonal"]
    )
    supported_spatial_aggregations: List[str] = field(
        default_factory=lambda: ["area_weighted"]
    )
    # New taxonomy field. Shape: ["<Domain>:<Sub-topic>", "<Use Case>", ...]
    # First domain is mirrored to `topic` for backward compat.
    categories: List[str] = field(default_factory=list)
    gaps: List[dict] = field(default_factory=list)

    def matches(self, query: str) -> bool:
        """Check if an identifier or alias matches this dataset case-insensitively."""
        q = (query or "").strip().lower()
        if q == self.dataset_id.lower():
            return True
        return any(q == alias.lower() for alias in self.aliases)


def _load_manifest(filename: str) -> Optional[dict]:
    manifest_path = DATA_DIR / "manifests" / filename
    if manifest_path.is_file():
        try:
            with open(manifest_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception as exc:
            logger.warning("Failed to parse manifest %s: %s", filename, exc)
            return None
    return None


